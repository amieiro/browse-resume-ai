#!/bin/sh
# Installs the Browse Resume AI native messaging host for Google Chrome (and Chromium on Linux)
# on macOS and Linux. On Windows, use install.ps1.
# Safe to run again (for example after moving the repository or upgrading Node or Claude Code).
set -eu

HOST_NAME="com.browse_resume_ai.host"
EXTENSION_ID="pdokiakaaeffjlabmofdppjakdhaimpi"

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
HOST_SCRIPT="$SCRIPT_DIR/host.mjs"

# Where the launcher goes, and the browsers' NativeMessagingHosts folders (one per line).
case "$(uname)" in
  Darwin)
    SUPPORT_DIR="$HOME/Library/Application Support/browse-resume-ai"
    MANIFEST_DIRS="$HOME/Library/Application Support/Google/Chrome/NativeMessagingHosts"
    ;;
  Linux)
    SUPPORT_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/browse-resume-ai"
    CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}"
    MANIFEST_DIRS="$CONFIG_DIR/google-chrome/NativeMessagingHosts
$CONFIG_DIR/chromium/NativeMessagingHosts"
    ;;
  *)
    echo "This installer supports macOS and Linux. On Windows, run native-host\\install.ps1 in PowerShell." >&2
    exit 1
    ;;
esac
LAUNCHER="$SUPPORT_DIR/launcher.sh"

NODE_BIN=$(command -v node || true)
CLAUDE_BIN=$(command -v claude || true)
CODEX_BIN=$(command -v codex || true)
if [ -z "$NODE_BIN" ]; then
  echo "Node.js was not found in PATH. Install Node 18 or later and run this script again." >&2
  exit 1
fi
if [ -z "$CLAUDE_BIN" ] && [ -z "$CODEX_BIN" ]; then
  echo "Neither Claude Code (claude) nor Codex (codex) was found in PATH. Install at least one, log in, and run this script again." >&2
  exit 1
fi
[ -n "$CLAUDE_BIN" ] || echo "Note: Claude Code (claude) was not found; the Claude provider will not work." >&2
[ -n "$CODEX_BIN" ] || echo "Note: Codex (codex) was not found; the Codex provider will not work." >&2

# PATH for the host: the directories of node, claude and codex, then the system ones.
HOST_PATH=$(dirname "$NODE_BIN")
for bin in "$CLAUDE_BIN" "$CODEX_BIN"; do
  [ -n "$bin" ] && HOST_PATH="$HOST_PATH:$(dirname "$bin")"
done
HOST_PATH="$HOST_PATH:/usr/bin:/bin:/usr/sbin:/sbin"

mkdir -p "$SUPPORT_DIR"

# Quotes a value for the launcher script: inside single quotes nothing is expanded, and a single
# quote is written as '\''. Paths may hold spaces, quotes, $ or backticks.
quote() {
  printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"
}

{
  printf '%s\n' '#!/bin/sh'
  printf '%s\n' '# Generated by browse-resume-ai native-host/install.sh. Chrome starts hosts with a minimal'
  printf '%s\n' '# environment, so absolute paths are fixed here.'
  printf '%s\n' "export PATH=$(quote "$HOST_PATH")"
  printf '%s\n' "export CLAUDE_BIN=$(quote "${CLAUDE_BIN:-/nonexistent/claude}")"
  printf '%s\n' "export CODEX_BIN=$(quote "${CODEX_BIN:-/nonexistent/codex}")"
  printf '%s\n' '# Claude Code finds its login (the macOS keychain, or the user'"'"'s files on Linux) by user name.'
  printf '%s\n' 'export USER="${USER:-$(/usr/bin/id -un)}"'
  printf '%s\n' 'export LOGNAME="${LOGNAME:-$USER}"'
  printf '%s\n' "exec $(quote "$NODE_BIN") $(quote "$HOST_SCRIPT") \"\$@\""
} > "$LAUNCHER"
chmod 755 "$LAUNCHER"

MANIFESTS=""
OLD_IFS=$IFS
IFS='
'
for dir in $MANIFEST_DIRS; do
  mkdir -p "$dir"
  # Node writes the JSON, so the launcher path is escaped whatever it contains.
  "$NODE_BIN" -e '
    const [file, name, path, id] = process.argv.slice(1);
    const manifest = { name, description: "Browse Resume AI local host", path, type: "stdio", allowed_origins: [`chrome-extension://${id}/`] };
    require("fs").writeFileSync(file, JSON.stringify(manifest, null, 2) + "\n");
  ' "$dir/$HOST_NAME.json" "$HOST_NAME" "$LAUNCHER" "$EXTENSION_ID"
  MANIFESTS="$MANIFESTS
  manifest: $dir/$HOST_NAME.json"
done
IFS=$OLD_IFS

echo "Installed $HOST_NAME"
echo "  node:     $NODE_BIN"
echo "  claude:   ${CLAUDE_BIN:-not found}"
echo "  codex:    ${CODEX_BIN:-not found}"
echo "  launcher: $LAUNCHER$MANIFESTS"
