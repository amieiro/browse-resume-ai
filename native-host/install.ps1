# Installs the Browse Resume AI native messaging host for Google Chrome and Chromium on Windows.
# Safe to run again (for example after moving the repository or upgrading Node or Claude Code).
#
# Run in PowerShell from the repository folder:
#   powershell -ExecutionPolicy Bypass -File native-host\install.ps1
param(
  # Where the launcher and the host manifest are written.
  [string]$DataDir = $(if ($env:LOCALAPPDATA) { Join-Path $env:LOCALAPPDATA 'browse-resume-ai' } else { '' }),
  # Do not register the host in the registry (used by the tests, which run outside Windows).
  [switch]$SkipRegistry
)
$ErrorActionPreference = 'Stop'

$HostName = 'com.browse_resume_ai.host'
$ExtensionId = 'pdokiakaaeffjlabmofdppjakdhaimpi'
$RegistryKeys = @(
  "HKCU:\Software\Google\Chrome\NativeMessagingHosts\$HostName",
  "HKCU:\Software\Chromium\NativeMessagingHosts\$HostName"
)
$Utf8NoBom = New-Object System.Text.UTF8Encoding $false

function Find-Command([string]$Name) {
  # Prefer a real executable; an npm .cmd shim is resolved below to the script it runs.
  foreach ($candidate in @("$Name.exe", "$Name.cmd", $Name)) {
    $command = Get-Command $candidate -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($command) { return $command.Source }
  }
  return $null
}

if (-not $DataDir) { throw 'LOCALAPPDATA is not set; pass -DataDir.' }

$NodeBin = Find-Command 'node'
if (-not $NodeBin) { throw 'Node.js was not found in PATH. Install Node 18 or later and run this script again.' }

$HostScript = Join-Path $PSScriptRoot 'host.mjs'
$Resolver = Join-Path $PSScriptRoot 'lib/resolve-cli.mjs'

# Node cannot start .cmd files without a shell, so a shim is replaced by the JavaScript it runs.
function Resolve-Cli([string]$Path) {
  if (-not $Path) { return $null }
  return (& $NodeBin $Resolver $Path)
}

$ClaudeBin = Resolve-Cli (Find-Command 'claude')
$CodexBin = Resolve-Cli (Find-Command 'codex')
if (-not $ClaudeBin -and -not $CodexBin) {
  throw 'Neither Claude Code (claude) nor Codex (codex) was found in PATH. Install at least one, log in, and run this script again.'
}
if (-not $ClaudeBin) { Write-Warning 'Claude Code (claude) was not found; the Claude provider will not work.' }
if (-not $CodexBin) { Write-Warning 'Codex (codex) was not found; the Codex provider will not work.' }

New-Item -ItemType Directory -Force -Path $DataDir | Out-Null
$Launcher = Join-Path $DataDir 'launcher.bat'
$Manifest = Join-Path $DataDir "$HostName.json"

# Chrome starts hosts with the user's environment, but PATH may lack nvm or npm folders.
$PathDirs = @($NodeBin, $ClaudeBin, $CodexBin) | Where-Object { $_ } | ForEach-Object { Split-Path -Parent $_ } | Select-Object -Unique
$LauncherLines = @(
  '@echo off',
  'rem Generated by browse-resume-ai native-host\install.ps1.',
  'chcp 65001 >nul 2>&1',
  "set `"PATH=$($PathDirs -join ';');%PATH%`"",
  "set `"CLAUDE_BIN=$(if ($ClaudeBin) { $ClaudeBin } else { 'C:\nonexistent\claude.exe' })`"",
  "set `"CODEX_BIN=$(if ($CodexBin) { $CodexBin } else { 'C:\nonexistent\codex.exe' })`"",
  "`"$NodeBin`" `"$HostScript`" %*"
)
[System.IO.File]::WriteAllText($Launcher, (($LauncherLines -join "`r`n") + "`r`n"), $Utf8NoBom)

$ManifestJson = [ordered]@{
  name            = $HostName
  description     = 'Browse Resume AI local host'
  path            = $Launcher
  type            = 'stdio'
  allowed_origins = @("chrome-extension://$ExtensionId/")
} | ConvertTo-Json
[System.IO.File]::WriteAllText($Manifest, $ManifestJson, $Utf8NoBom)

if (-not $SkipRegistry) {
  foreach ($key in $RegistryKeys) {
    New-Item -Path $key -Force | Out-Null
    Set-Item -Path $key -Value $Manifest
  }
}

Write-Output "Installed $HostName"
Write-Output "  node:     $NodeBin"
Write-Output "  claude:   $(if ($ClaudeBin) { $ClaudeBin } else { 'not found' })"
Write-Output "  codex:    $(if ($CodexBin) { $CodexBin } else { 'not found' })"
Write-Output "  launcher: $Launcher"
Write-Output "  manifest: $Manifest"
if (-not $SkipRegistry) { $RegistryKeys | ForEach-Object { Write-Output "  registry: $_" } }
